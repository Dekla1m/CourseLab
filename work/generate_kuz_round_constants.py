"""Generate only the fixed Ci lookup module; no other RTL is overwritten."""
from pathlib import Path

COEFFICIENTS = (148, 32, 133, 16, 194, 192, 1, 251,
                1, 192, 194, 16, 133, 32, 148, 1)


def multiply(a, b):
    result = 0
    for _ in range(8):
        if b & 1:
            result ^= a
        a = ((a << 1) & 255) ^ (0xC3 if a & 128 else 0)
        b >>= 1
    return result


def constant(index):
    block = list(index.to_bytes(16, "big"))
    for _ in range(16):
        feedback = 0
        for value, coefficient in zip(block, COEFFICIENTS):
            feedback ^= multiply(value, coefficient)
        block = [feedback] + block[:-1]
    return bytes(block).hex()


def main():
    target = Path(__file__).resolve().parents[1] / "CourseLab.srcs/sources_1/kuz_round_constant.v"
    lines = [
        "// Fixed Kuznyechik key-schedule constants: Ci = L(Vec128(i)).",
        "// Generated by work/generate_kuz_round_constants.py; indices 1..32.",
        "`timescale 1ns/1ps",
        "`default_nettype none",
        "module kuz_round_constant (",
        "    input wire [5:0] iteration_index,",
        "    output reg [127:0] iteration_constant",
        ");",
        "    always @* begin",
        "        case (iteration_index)",
    ]
    lines += [f"            6'd{i}: iteration_constant = 128'h{constant(i)};" for i in range(1, 33)]
    lines += ["            default: iteration_constant = 128'b0;",
              "        endcase", "    end", "endmodule", "`default_nettype wire", ""]
    target.write_text("\n".join(lines), encoding="ascii")
    print(f"Generated 32 constants in {target}")


if __name__ == "__main__":
    main()
